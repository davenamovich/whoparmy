#!/usr/bin/env node
/**
 * Regenerate src/lib/marketplace-bundle-files.ts — the embedded copy of
 * the first-purchase marketplace bundle skill (space-demo-and-replicate,
 * whose Step 2 is the demo-recording skill) that getBundleKit serves to
 * a granted buyer's Muse through the bridge.
 *
 * Source of truth: the house skill folder (default
 * ~/workspace/custom-skills/space-demo-and-replicate). Run after editing
 * that skill so the served copy never drifts:
 *
 *   node scripts/generate-bundle-skill.mjs [sourceDir]
 *
 * The generated module is checked in; the bundle tests byte-compare the
 * embedded copy against the source folder when it is readable.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const sourceDir = process.argv[2] ?? join(homedir(), "workspace/custom-skills/space-demo-and-replicate");
const outPath = fileURLToPath(new URL("../src/lib/marketplace-bundle-files.ts", import.meta.url));

const files = [];
const walk = (dir) => {
  for (const entry of readdirSync(dir).sort()) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full);
    else files.push({ path: relative(sourceDir, full).split("\\").join("/"), text: readFileSync(full, "utf8") });
  }
};
walk(sourceDir);
if (!files.some((f) => f.path === "SKILL.md")) throw new Error(`No SKILL.md found in ${sourceDir}`);

const body = `/**
 * GENERATED by scripts/generate-bundle-skill.mjs — do not edit by hand.
 * Embedded copy of the house space-demo-and-replicate skill folder (the
 * first-purchase marketplace bundle: the replicator skill, whose Step 2
 * is the demo-recording skill). Served only to bundle-granted buyers
 * through the bridge bundle-kit route. Regenerate after editing the
 * source skill; the bundle tests byte-compare against the source.
 */
export const BUNDLE_SKILL_FILES: Array<{ path: string; text: string }> = ${JSON.stringify(files, null, 2)};
`;
writeFileSync(outPath, body);
console.log(`Wrote ${outPath} with ${files.length} file(s) from ${sourceDir}`);
