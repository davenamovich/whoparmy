/**
 * ─── FIRST-PURCHASE BUNDLE DELIVERY — pure core ───
 *
 * The marketplace bundle promise (M2): a member's first paid listing fee
 * grants the bundle — the replicator skill plus the demo-recording
 * skill. Until 2026-11-25 the grant was only a timestamp flag
 * (User.marketplaceBundleAt) plus two skill NAMES in getBundle; no
 * route served the files, so a granted buyer's Muse could not obtain
 * the skills it had just been promised (audit
 * reports/replicate-packages-audit-2026-11-25.md §3).
 *
 * The delivery follows the M3 kit-download pattern (getKitForBuyer →
 * canDownloadKit gate → { kit: { files } }): the granted buyer fetches
 * the real skill files through the bridge bundle-kit route, gated on
 * the grant. Both promised "skills" live in one folder:
 * space-demo-and-replicate IS the replicator, and the demo-recording
 * skill is its Step 2 — so the kit ships that folder, paths namespaced
 * by the skill name like every other replication kit.
 *
 * The file contents are embedded at build time from the house skill
 * folder (src/lib/marketplace-bundle-files.ts, generated by
 * scripts/generate-bundle-skill.mjs) because the app server has no
 * access to the workspace filesystem in production.
 */
import { BUNDLE_SKILL_FILES } from "@/lib/marketplace-bundle-files";
import type { Bundle } from "@/lib/marketplace";

export const BUNDLE_SKILL_NAME = "space-demo-and-replicate";

/** The two skills the bundle has always promised, now with real files behind the names. */
export const BUNDLE_SKILLS: Array<{ name: string; note: string }> = [
  { name: BUNDLE_SKILL_NAME, note: "replicator" },
  { name: BUNDLE_SKILL_NAME, note: "demo recording (Step 2 of space-demo-and-replicate)" },
];

/** Bridge route a granted buyer's Muse fetches the bundle files from. */
export const BUNDLE_KIT_PATH = "/api/bridge/marketplace/bundle/kit";

/** The bundle gate, mirroring canDownloadKit's shape: the grant flag is the whole key. */
export function canDownloadBundle(input: { granted: boolean }): boolean {
  return input.granted;
}

/** The downloadable bundle kit: the real skill folder, paths namespaced by skill name. */
export function bundleKit(): Bundle {
  return { files: BUNDLE_SKILL_FILES.map((f) => ({ path: `${BUNDLE_SKILL_NAME}/${f.path}`, text: f.text })) };
}
